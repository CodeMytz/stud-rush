// Generates contracts/DealTable.sol: 8 hand-checkable variants of 4 deals for each of the 5 rounds.
// Every variant has ONE clearly best deal (margin >= 3 pts), the best deal is never the highest rate,
// and from round 3 on, ranking by simple interest (rate x periods) gives the wrong answer.
const fs = require("fs");
const path = require("path");

let s = 0x9e3779b9; // deterministic PRNG so the table is reproducible
const rnd = () => ((s = (Math.imul(s ^ (s >>> 15), 0x2c1b3c6d) + 0x297a2d39) >>> 0), s / 2 ** 32);
const int = (a, b) => a + Math.floor(rnd() * (b - a + 1));

const P = 1000n * 10n ** 18n;
const value = (d) => {
  let a = P;
  for (let i = 0; i < d.periods; i++) a = (a * (10000n + BigInt(d.rate))) / 10000n;
  const gross = a - P, fee = (P * BigInt(d.fee)) / 10000n;
  return gross > fee ? gross - fee : 0n;
};
const pts = (v) => Number(v / 10n ** 16n) / 100;
const maxPeriods = [5, 8, 11, 14, 18];
const minPeriods = [2, 2, 3, 3, 4];

function candidate(r) {
  return Array.from({ length: 4 }, () => ({
    rate: int(16, 64) * 25,            // 4.00% .. 16.00%
    periods: int(minPeriods[r], maxPeriods[r]),
    fee: int(0, 24) * 25,              // 0 .. 6.00% of 1000 = 0 .. 60 pts
  }));
}
function ok(r, set) {
  const v = set.map(value);
  if (v.some((x) => pts(x) < 5)) return false;
  const order = v.map((x, i) => i).sort((a, b) => (v[b] > v[a] ? 1 : -1));
  const best = order[0];
  if (pts(v[best] - v[order[1]]) < 3) return false;
  const maxRate = Math.max(...set.map((d) => d.rate));
  if (set[best].rate === maxRate) return false;
  if (new Set(set.map((d) => d.rate)).size < 4) return false;
  if (r >= 2) {
    const simple = set.map((d) => (1000 * d.rate * d.periods) / 10000 - d.fee / 10);
    if (simple.indexOf(Math.max(...simple)) === best) return false;
  }
  return true;
}

const bytes = [];
for (let r = 0; r < 5; r++) {
  const seen = new Set();
  let v = 0;
  while (v < 8) {
    const set = candidate(r);
    const key = JSON.stringify(set);
    if (seen.has(key) || !ok(r, set)) continue;
    seen.add(key); v++;
    for (const d of set) bytes.push(d.rate >> 8, d.rate & 255, d.periods, d.fee >> 8, d.fee & 255);
  }
}
const hex = Buffer.from(bytes).toString("hex");
const sol = `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.27;

/// @dev GENERATED by scripts/gen-deals.cjs. Do not edit by hand.
/// Layout: round (5) x variant (8) x slot (4) x [rate u16 | periods u8 | feeBps u16] = 800 bytes.
library DealTable {
    uint256 internal constant VARIANTS = 8;
    bytes internal constant TABLE = hex"${hex}";

    function read(uint256 round, uint256 variant, uint256 slot)
        internal pure returns (uint16 rate, uint8 periods, uint16 feeBps)
    {
        uint256 o = ((round * VARIANTS + variant) * 4 + slot) * 5;
        rate = (uint16(uint8(TABLE[o])) << 8) | uint16(uint8(TABLE[o + 1]));
        periods = uint8(TABLE[o + 2]);
        feeBps = (uint16(uint8(TABLE[o + 3])) << 8) | uint16(uint8(TABLE[o + 4]));
    }
}
`;
fs.writeFileSync(path.join(__dirname, "..", "contracts", "DealTable.sol"), sol);
console.log("DealTable.sol written,", bytes.length, "bytes");
